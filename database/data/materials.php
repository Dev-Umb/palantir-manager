$dimensions = static function (string $size): array {
    if (preg_match('/^(\d+(?:\.\d+)?)×(\d+(?:\.\d+)?)$/u', $size, $matches)) {
        return [(float) $matches[2], (float) $matches[1]];
    }

    if (preg_match('/^\d+(?:\.\d+)?$/', $size)) {
        return [(float) $size, null];
    }

    return [null, null];
};

